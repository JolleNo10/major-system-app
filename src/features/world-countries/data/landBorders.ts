const LAND_BORDER_ADJACENCY = createLandBorderAdjacency(LAND_BORDER_PAIRS)

/** Return the canonical land-border neighbours for one Country. */
export function getLandBorderNeighbourIds(countryId: CountryId): CountryId[] {
  return [...(LAND_BORDER_ADJACENCY.get(countryId) ?? [])]
}

/**
 * Filter canonical edges to the supplied active Country population.
 * Disabled entities are removed; their neighbours are never contracted.
 */
export function getEffectiveLandBorderNeighbourIds(
  countryId: CountryId,
  activeCountryIds: readonly CountryId[],
): CountryId[] {
  const activeIds = new Set(activeCountryIds)
  return getLandBorderNeighbourIds(countryId).filter(neighbourId => activeIds.has(neighbourId))
}

export function hasEffectiveLandBorderNeighbours(
  countryId: CountryId,
  activeCountryIds: readonly CountryId[],
): boolean {
  return getEffectiveLandBorderNeighbourIds(countryId, activeCountryIds).length > 0
}

function createLandBorderAdjacency(
  pairs: readonly LandBorderPair[],
): ReadonlyMap<CountryId, readonly CountryId[]> {
  const adjacency = new Map<CountryId, CountryId[]>()
  for (const [left, right] of pairs) {
    const leftNeighbours = adjacency.get(left) ?? []
    const rightNeighbours = adjacency.get(right) ?? []
    leftNeighbours.push(right)
    rightNeighbours.push(left)
    adjacency.set(left, leftNeighbours)
    adjacency.set(right, rightNeighbours)
  }
  return new Map([...adjacency.entries()].map(([countryId, neighbourIds]) => [countryId, [...neighbourIds]] as const))
}
